"""Document Classifier Lambda (megazone-idp)

Runs in PostAnalysisParallel, after the document summary is available.
Assigns an auto-classification category path (e.g. "인사/규정") to the document
so the web UI can render an auto-generated folder tree for non-technical users.

Design notes:
- Best-effort: any failure is swallowed and returns success, so classification
  never fails the document-processing workflow.
- Consistency: reads the project's existing category taxonomy and instructs the
  model to reuse an existing category when it fits, otherwise propose a new one
  (max 3 levels deep). New categories are registered back into the taxonomy.
- Signal: uses the document summary (already generated by document-summarizer).
"""
import json
import os

import boto3

from shared.ddb_client import (
    get_document,
    get_project_categories,
    get_project_language,
    update_document_category,
)
from shared.s3_analysis import get_summary

MAX_DEPTH = 3
FALLBACK_CATEGORY = '미분류'

# megazone-idp: a FIXED set of allowed top-level domains. The classifier runs
# per-document in independent Step Functions executions, so concurrent documents
# cannot see each other's freshly-written categories (the per-project taxonomy
# only converges for documents processed strictly after earlier ones committed).
# Constraining the top level to this fixed list makes documents of the same
# domain land in the same top-level folder regardless of ordering — the single
# biggest lever for consistent classification. Sub-levels stay free-form.
TOP_LEVEL_DOMAINS = [
    'Infrastructure', 'Development', 'Security', 'Data', 'HR', 'Finance',
    'Sales', 'Marketing', 'Legal', 'Planning', 'Operations', 'Support',
    'General',
]

_bedrock = None


def get_bedrock():
    global _bedrock
    if _bedrock is None:
        _bedrock = boto3.client(
            'bedrock-runtime',
            region_name=os.environ.get('AWS_REGION', 'us-east-1'),
        )
    return _bedrock


def normalize_category_path(raw: str) -> str:
    """Normalize a model-produced category path into a clean '/'-joined path.

    - trims each segment, drops empties, collapses separators
    - caps depth at MAX_DEPTH
    - falls back to FALLBACK_CATEGORY when nothing usable remains
    """
    if not raw:
        return FALLBACK_CATEGORY
    parts = [p.strip() for p in str(raw).replace('\\', '/').split('/')]
    parts = [p for p in parts if p and p not in ('.', '..')]
    if not parts:
        return FALLBACK_CATEGORY
    return '/'.join(parts[:MAX_DEPTH])


def build_prompt(summary_text: str, existing_categories: list, language: str,
                 file_name: str = '', folder_path: str = '') -> str:
    cats = (
        '\n'.join(f'- {c}' for c in existing_categories)
        or '(none yet — you may create the first folders)'
    )
    ctx = ''
    if file_name:
        ctx += f'File name: {file_name}\n'
    if folder_path:
        ctx += f'Original upload folder: {folder_path}\n'
    return (
        'You are a document librarian organizing a company document library into a '
        'clean, CONSISTENT folder taxonomy. Classify the document by its PRIMARY '
        'SUBJECT and DOMAIN (what it is fundamentally about) — not by incidental '
        'words that merely appear in the text.\n\n'
        f'Existing category folders (reuse a sub-path when the document fits):\n{cats}\n\n'
        'Rules:\n'
        f'- The TOP-LEVEL folder MUST be exactly one of these {len(TOP_LEVEL_DOMAINS)} '
        'fixed domains (keep the same domain, but write its label in the target '
        f'language): {", ".join(TOP_LEVEL_DOMAINS)}.\n'
        '- Choosing the correct fixed top-level domain is the MOST important part: '
        'documents about the same domain MUST share the same top-level folder. This '
        'is what keeps the taxonomy consistent across documents.\n'
        '- Then add 1-2 more specific sub-levels below it. At most 3 levels total.\n'
        '- Reuse an existing sub-path when it genuinely fits; otherwise create a new, '
        'more appropriate one. Do NOT force-fit into an existing path.\n'
        '- Technical/config/IaC artifacts (Terraform/tfplan, YAML, Dockerfile, shell '
        'or code files, build/deploy logs) belong under Infrastructure or Development, '
        'NOT under Support unless the document is actually a customer/IT support ticket '
        'or an incident report.\n'
        '- Use the file name and upload folder only as HINTS about the domain — do NOT '
        'copy the upload folder name as the category; classify by subject.\n'
        f'- Write all folder names in this language code: {language}.\n'
        '- If genuinely unsure, use the correct fixed top-level with a low confidence '
        'rather than an oddly specific wrong path.\n'
        '- Respond ONLY with JSON: {"category_path": "...", "confidence": 0.0-1.0}\n\n'
        f'{ctx}'
        f'Document summary:\n{summary_text[:6000]}'
    )


def classify(summary_text: str, existing_categories: list, language: str,
             model_id: str, region: str, file_name: str = '',
             folder_path: str = '') -> tuple:
    """Return (category_path, confidence). Never raises — falls back on error."""
    try:
        prompt = build_prompt(
            summary_text, existing_categories, language, file_name, folder_path
        )
        resp = get_bedrock().converse(
            modelId=model_id,
            messages=[{'role': 'user', 'content': [{'text': prompt}]}],
            inferenceConfig={'maxTokens': 512, 'temperature': 0.0},
        )
        text = resp['output']['message']['content'][0]['text'].strip()
        # tolerate ```json fences / surrounding prose
        start, end = text.find('{'), text.rfind('}')
        data = json.loads(text[start:end + 1]) if start != -1 and end != -1 else {}
        path = normalize_category_path(data.get('category_path', ''))
        conf = data.get('confidence')
        conf = float(conf) if isinstance(conf, (int, float)) else None
        return path, conf
    except Exception as e:  # noqa: BLE001 - best-effort
        print(f'Classification failed, using fallback: {e}')
        return FALLBACK_CATEGORY, None


def handler(event, context):
    print(f'Event: {json.dumps(event)}')

    project_id = event.get('project_id')
    document_id = event.get('document_id')
    file_uri = event.get('file_uri')
    model_id = os.environ.get('CLASSIFIER_MODEL_ID', '')
    region = os.environ.get('AWS_REGION', 'us-east-1')

    if not (project_id and document_id and file_uri and model_id):
        print('Missing required input; skipping classification')
        return {**event, 'category_path': None}

    try:
        summary = get_summary(file_uri) or {}
        summary_text = summary.get('document_summary', '')
        if not summary_text:
            print('No summary available; skipping classification')
            return {**event, 'category_path': None}

        language = get_project_language(project_id) or 'en'
        existing = get_project_categories(project_id)
        doc = get_document(project_id, document_id)
        file_name = doc.get('file_name', '') or doc.get('name', '')
        folder_path = doc.get('folder_path', '') or ''

        # megazone-idp: category_path is now a PURE semantic classification.
        # The uploaded folder structure is shown separately via the "폴더" toggle
        # in the UI (folder_path), so we no longer root the category under the
        # upload folder — folder_path is passed to the model only as a hint.
        category_path, confidence = classify(
            summary_text, existing, language, model_id, region,
            file_name, folder_path,
        )

        update_document_category(project_id, document_id, category_path, confidence)
        print(f'Classified {document_id} -> {category_path} (conf={confidence})')
        return {**event, 'category_path': category_path}
    except Exception as e:  # noqa: BLE001 - best-effort, never fail the workflow
        print(f'Classifier error (non-fatal): {e}')
        return {**event, 'category_path': None}


def _demo():
    """megazone-idp self-check: path normalization edge cases."""
    assert normalize_category_path('인사/규정') == '인사/규정'
    assert normalize_category_path(' 재무 / 2024 / 보고서 / 세부 ') == '재무/2024/보고서'
    assert normalize_category_path('') == FALLBACK_CATEGORY
    assert normalize_category_path('///') == FALLBACK_CATEGORY
    assert normalize_category_path('a\\b') == 'a/b'
    # fixed domains must be slash-free, else they'd break path splitting
    assert all('/' not in d for d in TOP_LEVEL_DOMAINS)
    # the fixed domain list must actually reach the model prompt
    p = build_prompt('some summary', [], 'ko', 'plan.tf', 'nanoh2o')
    assert 'Infrastructure' in p and 'nanoh2o' in p
    print('document-classifier self-check passed')


if __name__ == '__main__':
    _demo()
